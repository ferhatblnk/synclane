using System.Text;
using SyncLane.Storage;

namespace SyncLane;

/// <summary>
/// The SQL SyncLane needs, for teams that apply migrations themselves. Put <see cref="Script"/> into your own migration
/// (for example <c>migrationBuilder.Sql(SyncLaneSchema.Script())</c> in EF Core) and set
/// <see cref="SyncLaneOptions.CreateSchema"/> to <c>false</c>.
/// </summary>
public static class SyncLaneSchema
{
    /// <summary>The newest schema version this SyncLane knows.</summary>
    public static int LatestVersion => Migrations.Latest;

    /// <summary>
    /// A script that brings the schema to <see cref="LatestVersion"/> from any earlier version, including from nothing.
    /// It is safe to run more than once. It does not wrap itself in a transaction; run it inside yours.
    /// </summary>
    /// <param name="schema">The schema the jobs table lives in, the same value as <see cref="SyncLaneOptions.Schema"/>.</param>
    public static string Script(string schema = "synclane")
    {
        if (!SchemaName.IsValid(schema))
            throw new ArgumentException(SyncLaneErrors.SchemaNameInvalid(schema).ToString(), nameof(schema));

        var script = new StringBuilder()
            .AppendLine($"-- SyncLane schema, version {Migrations.Latest}.")
            .AppendLine($"-- Generated by SyncLaneSchema.Script(\"{schema}\"). Safe to run more than once.")
            .AppendLine()
            .AppendLine(Migrations.HistoryTable(schema));

        foreach (var migration in Migrations.All)
        {
            script.AppendLine()
                .AppendLine($"-- {migration.Version}: {migration.Name}")
                .AppendLine()
                .AppendLine(migration.Sql(schema))
                .AppendLine()
                .AppendLine(Migrations.Record(schema, migration));
        }

        return script.ToString();
    }
}
